//! EdgeRun system UI overlay for the compositor CPU scanout path.
//!
//! Renders directly into an XRGB8888 dumb buffer using simple pixel
//! operations. This is intentionally self-contained so the compositor
//! does not need to depend on the full edgerun-ui-core GPU scene API
//! for a simple diagnostic overlay.

#[derive(Clone, Copy)]
struct Rgba {
    r: u8,
    g: u8,
    b: u8,
    a: u8,
}

fn blend(src: Rgba, dst: &mut [u8]) {
    let a = src.a as u32;
    let inv = 255u32.wrapping_sub(a);
    dst[0] = ((src.b as u32 * a + dst[0] as u32 * inv) / 255) as u8;
    dst[1] = ((src.g as u32 * a + dst[1] as u32 * inv) / 255) as u8;
    dst[2] = ((src.r as u32 * a + dst[2] as u32 * inv) / 255) as u8;
}

fn set_pixel(pixels: &mut [u8], pitch: u32, x: i32, y: i32, color: Rgba) {
    let px = x.max(0) as u32;
    let py = y.max(0) as u32;
    let row_bytes = pitch as usize;
    let off = py as usize * row_bytes + px as usize * 4;
    if off + 3 < pixels.len() {
        blend(color, &mut pixels[off..off + 3]);
    }
}

fn fill_rect(pixels: &mut [u8], pitch: u32, x: i32, y: i32, w: u32, h: u32, color: Rgba) {
    let fb_w = (pitch / 4) as i32;
    let fb_h = (pixels.len() / pitch as usize) as i32;
    let x0 = x.max(0).min(fb_w);
    let y0 = y.max(0).min(fb_h);
    let x1 = (x + w as i32).max(0).min(fb_w);
    let y1 = (y + h as i32).max(0).min(fb_h);
    for py in y0..y1 {
        let row = py as usize * pitch as usize;
        for px in x0..x1 {
            let off = row + px as usize * 4;
            if off + 3 < pixels.len() {
                blend(color, &mut pixels[off..off + 3]);
            }
        }
    }
}

fn draw_text(
    pixels: &mut [u8],
    pitch: u32,
    x: i32,
    y: i32,
    text: &str,
    color: Rgba,
) {
    let font = FONT_8X8;
    for (ci, ch) in text.bytes().enumerate() {
        if ch < 0x20 || ch > 0x7E {
            continue;
        }
        let glyph = font[(ch - 0x20) as usize];
        for row in 0..8 {
            let bits = glyph[row];
            for col in 0..8 {
                if (bits >> (7 - col)) & 1 != 0 {
                    set_pixel(pixels, pitch, x + ci as i32 * 9 + col as i32, y + row as i32, color);
                }
            }
        }
    }
}

const BG: Rgba = Rgba { r: 18, g: 18, b: 22, a: 220 };
const TEXT_COLOR: Rgba = Rgba { r: 230, g: 230, b: 240, a: 255 };
const MUTED: Rgba = Rgba { r: 140, g: 140, b: 155, a: 255 };
const ACCENT: Rgba = Rgba { r: 100, g: 140, b: 255, a: 255 };
const GREEN: Rgba = Rgba { r: 80, g: 250, b: 123, a: 255 };
const CYAN: Rgba = Rgba { r: 139, g: 233, b: 253, a: 255 };
const WHITE: Rgba = Rgba { r: 255, g: 255, b: 255, a: 255 };

/// Draw the EdgeRun native command-center overlay into the caller-owned
/// scanout buffer.
pub fn draw_system_ui_overlay(pixels: &mut [u8], width: u32, height: u32, pitch: u32) {
    if pixels.is_empty() || width == 0 || height == 0 || pitch < width.saturating_mul(4) {
        return;
    }

    let margin = 18i32;
    let panel_w = (width as i32 - margin * 2).min(620);
    let panel_h = 190;

    // Top bar
    fill_rect(pixels, pitch, 0, 0, width, 84, Rgba { r: 0, g: 0, b: 0, a: 72 });

    // Panel background
    fill_rect(pixels, pitch, margin, margin, panel_w as u32, panel_h as u32, BG);

    // Title
    draw_text(pixels, pitch, margin + 20, margin + 18, "EdgeRun", WHITE);
    draw_text(
        pixels,
        pitch,
        margin + 22,
        margin + 66,
        "native compositor / no DOM / no CSS",
        MUTED,
    );

    // Badge
    let badge_x = margin + panel_w - 110;
    let badge_y = margin + 22;
    fill_rect(pixels, pitch, badge_x, badge_y, 86, 24, ACCENT);
    draw_text(pixels, pitch, badge_x + 8, badge_y + 8, "native", BG);

    // Stat chips
    let chip_y = margin + 108;
    stat_chip(pixels, pitch, margin + 22, chip_y, 132, "runtime", "ready", ACCENT);
    stat_chip(pixels, pitch, margin + 166, chip_y, 132, "renderer", "cpu", CYAN);
    stat_chip(pixels, pitch, margin + 310, chip_y, 132, "mesh", "online", GREEN);

    // Buttons at bottom of panel
    let btn_y = margin + panel_h - 48;
    let btn_w = 98u32;
    fill_rect(pixels, pitch, margin + panel_w - 230, btn_y, btn_w, 32, BG);
    draw_text(pixels, pitch, margin + panel_w - 222, btn_y + 10, "Trust", TEXT_COLOR);
    fill_rect(pixels, pitch, margin + panel_w - 120, btn_y, 96, 32, ACCENT);
    draw_text(pixels, pitch, margin + panel_w - 110, btn_y + 10, "Open", BG);
}

fn stat_chip(
    pixels: &mut [u8],
    pitch: u32,
    x: i32,
    y: i32,
    w: u32,
    label: &str,
    value: &str,
    accent: Rgba,
) {
    let fill = Rgba { r: 30, g: 30, b: 36, a: 224 };
    fill_rect(pixels, pitch, x, y, w, 48, fill);
    fill_rect(pixels, pitch, x, y, 3, 48, accent);
    draw_text(pixels, pitch, x + 12, y + 8, label, MUTED);
    draw_text(pixels, pitch, x + 12, y + 26, value, TEXT_COLOR);
}

