fn draw_char_2x(pixels: &mut [u8], x: usize, y: usize, c: u8, pitch: usize, color: u32) {
    if c < 0x20 || c > 0x7E {
        return;
    }
    let glyph = FONT[(c - 0x20) as usize];
    let px_width = pitch / 4;
    let py_height = pixels.len() / pitch;
    for row in 0..8 {
        let bits = glyph[row];
        for col in 0..8 {
            if (bits >> (7 - col)) & 1 != 0 {
                for dy in 0..2 {
                    for dx in 0..2 {
                        let px = x + col * 2 + dx;
                        let py = y + row * 2 + dy;
                        if px >= px_width || py >= py_height {
                            continue;
                        }
                        let off = (py * px_width + px) * 4;
                        if off + 3 < pixels.len() {
                            pixels[off] = (color & 0xFF) as u8;
                            pixels[off + 1] = ((color >> 8) & 0xFF) as u8;
                            pixels[off + 2] = ((color >> 16) & 0xFF) as u8;
                            pixels[off + 3] = 0xFF;
                        }
                    }
                }
            }
        }
    }
}

fn draw_text(pixels: &mut [u8], x: usize, y: usize, text: &str, pitch: usize, color: u32) {
    let px_width = pitch / 4;
    let mut cx = x;
    for byte in text.bytes() {
        if byte == b'\n' {
            cx = x;
            continue;
        }
        if cx + 16 > px_width {
            break;
        }
        draw_char_2x(pixels, cx, y, byte, pitch, color);
        cx += 16;
    }
}
