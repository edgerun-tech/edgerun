//! Test overlay — renders text directly on the framebuffer.

use std::collections::VecDeque;

const MAX_LINES: usize = 60;

pub struct TestOverlay {
    lines: VecDeque<(String, u32)>,
}

/// XRGB8888 little-endian: [B, G, R, X]
pub const COLOR_GREEN: u32 = 0xFF00FF00;
pub const COLOR_YELLOW: u32 = 0xFF00FFFF;
pub const COLOR_RED: u32 = 0xFF0000FF;
pub const COLOR_CYAN: u32 = 0xFFFFFF00;
pub const COLOR_WHITE: u32 = 0xFFFFFFFF;
pub const COLOR_GRAY: u32 = 0xFF888888;

impl TestOverlay {
    pub fn new() -> Self {
        Self {
            lines: VecDeque::with_capacity(MAX_LINES + 10),
        }
    }

    pub fn is_empty(&self) -> bool {
        self.lines.is_empty()
    }

    pub fn add_line(&mut self, text: &str, color: u32) {
        if self.lines.len() >= MAX_LINES {
            self.lines.pop_front();
        }
        self.lines.push_back((text.to_string(), color));
    }

    pub fn separator(&mut self) {
        self.add_line(&"─".repeat(90), COLOR_GRAY);
    }

    pub fn render(&self, pixels: &mut [u8], pitch: u32, _fb_width: u32, _fb_height: u32) {
        let char_h = 16;
        let px_width = pitch as usize / 4;
        let rows = self.lines.len().min(60);
        if rows == 0 || px_width == 0 {
            return;
        }

        // Darken background panel (30% of original)
        let panel_bottom = rows * char_h;
        for py in 0..panel_bottom {
            for px in 0..px_width {
                let off = (py * px_width + px) * 4;
                if off + 3 < pixels.len() {
                    pixels[off] = (pixels[off] as u32 * 3 / 10) as u8;
                    pixels[off + 1] = (pixels[off + 1] as u32 * 3 / 10) as u8;
                    pixels[off + 2] = (pixels[off + 2] as u32 * 3 / 10) as u8;
                }
            }
        }

        // Render lines
        for (i, (line, color)) in self.lines.iter().enumerate().take(rows) {
            let y = i * char_h;
            draw_text(pixels, 0, y, line, pitch as usize, *color);
        }
    }
}

