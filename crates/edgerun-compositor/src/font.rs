/// Draw an 8x8 character at the given position.
pub fn draw_char(pixels: &mut [u8], x: usize, y: usize, c: u8, pitch: usize, color: u32) {
    if c < 0x20 || c > 0x7E {
        return;
    }
    let glyph = FONT[(c - 0x20) as usize];
    for row in 0..8usize {
        if y + row >= (pixels.len() / 4) / (pitch / 4) {
            return;
        }
        let bits = glyph[row];
        for col in 0..8usize {
            let px = x + col;
            let py = y + row;
            if px >= pitch / 4 {
                return;
            }
            if (bits >> (7 - col)) & 1 != 0 {
                let off = (py * (pitch / 4) + px) * 4;
                if off + 3 < pixels.len() {
                    // color is XRGB8888 LE: [B, G, R, X]
                    pixels[off] = (color & 0xFF) as u8;
                    pixels[off + 1] = ((color >> 8) & 0xFF) as u8;
                    pixels[off + 2] = ((color >> 16) & 0xFF) as u8;
                    pixels[off + 3] = 0xFF;
                }
            }
        }
    }
}

/// Draw a string at the given position (16x8 font = 2x scale).
pub fn draw_text(pixels: &mut [u8], x: usize, y: usize, text: &str, pitch: usize, color: u32) {
    let mut cx = x;
    for byte in text.bytes() {
        if byte == b'\n' {
            cx = x;
            continue;
        }
        if cx + 16 > pitch / 4 {
            break;
        }
        draw_char_2x(pixels, cx, y, byte, pitch, color);
        cx += 16;
    }
}

/// Draw a character at 2x scale (16x16 pixels).
fn draw_char_2x(pixels: &mut [u8], x: usize, y: usize, c: u8, pitch: usize, color: u32) {
    if c < 0x20 || c > 0x7E {
        return;
    }
    let glyph = FONT[(c - 0x20) as usize];
    for row in 0..8usize {
        let bits = glyph[row];
        for col in 0..8usize {
            if (bits >> (7 - col)) & 1 != 0 {
                // Fill 2x2 block
                for dy in 0..2 {
                    for dx in 0..2 {
                        let px = x + col * 2 + dx;
                        let py = y + row * 2 + dy;
                        if px >= pitch / 4 {
                            continue;
                        }
                        if py >= pixels.len() / pitch {
                            continue;
                        }
                        let off = (py * (pitch / 4) + px) * 4;
                        if off + 3 < pixels.len() {
                            pixels[off] = (color & 0xFF) as u8;
                            pixels[off + 1] = ((color >> 8) & 0xFF) as u8;
                            pixels[off + 2] = ((color >> 16) & 0xFF) as u8;
                            pixels[off + 3] = 0xFF;
                        }
                    }
                }
            }
        }
    }
}
