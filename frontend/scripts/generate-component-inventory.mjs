#!/usr/bin/env node
import { readdirSync, readFileSync, statSync, writeFileSync } from "node:fs"
import { join, relative, sep } from "node:path"

const root = process.cwd()
const componentsDir = join(root, "components")
const featuresDir = join(root, "features")
const outputPath = join(root, "COMPONENT_INVENTORY.md")
const jsonOutputPath = join(root, "COMPONENT_INVENTORY.json")

const IGNORED_DIRS = new Set(["node_modules", ".next", "out", "coverage", ".git"])
const COMPONENT_EXT = new Set([".tsx", ".ts", ".jsx", ".js"])

function extname(path) {
  const idx = path.lastIndexOf(".")
  return idx >= 0 ? path.slice(idx) : ""
}

function walk(dir, files = []) {
  for (const name of readdirSync(dir)) {
    if (IGNORED_DIRS.has(name)) continue
    const path = join(dir, name)
    const stat = statSync(path)
    if (stat.isDirectory()) {
      walk(path, files)
    } else if (COMPONENT_EXT.has(extname(path))) {
      files.push(path)
    }
  }
  return files
}

function readExports(path) {
  const text = readFileSync(path, "utf8")
  const exports = new Set()

  for (const match of text.matchAll(/export\s+function\s+([A-Za-z0-9_]+)/g)) exports.add(match[1])
  for (const match of text.matchAll(/export\s+const\s+([A-Za-z0-9_]+)/g)) exports.add(match[1])
  for (const match of text.matchAll(/export\s+class\s+([A-Za-z0-9_]+)/g)) exports.add(match[1])
  for (const match of text.matchAll(/export\s+type\s+([A-Za-z0-9_]+)/g)) exports.add(`type ${match[1]}`)
  for (const match of text.matchAll(/export\s+interface\s+([A-Za-z0-9_]+)/g)) exports.add(`interface ${match[1]}`)

  if (/export\s+default\s+/.test(text)) exports.add("default export")
  return Array.from(exports).sort()
}

function groupFor(path) {
  const rel = relative(root, path).split(sep).join("/")
  if (rel.startsWith("components/ui/")) return "components/ui"
  if (rel.startsWith("components/layouts/")) return "layouts"
  if (rel.startsWith("components/sections/")) return "sections"
  if (rel.startsWith("components/apps/")) return "apps"
  if (rel.startsWith("components/os/")) return "os-shell"
  if (rel.startsWith("components/previews/")) return "previews"
  if (rel.startsWith("features/")) return rel.split("/").slice(0, 2).join("/")
  if (rel.includes("demo")) return "review/cleanup"
  return "components/other"
}

const roots = [componentsDir, featuresDir].filter((dir) => {
  try {
    return statSync(dir).isDirectory()
  } catch {
    return false
  }
})

const entries = roots.flatMap((dir) => walk(dir)).map((path) => ({
  path: relative(root, path).split(sep).join("/"),
  group: groupFor(path),
  exports: readExports(path),
}))

const groups = new Map()
for (const entry of entries) {
  if (!groups.has(entry.group)) groups.set(entry.group, [])
  groups.get(entry.group).push(entry)
}

const lines = []
lines.push("# Component Inventory")
lines.push("")
lines.push("Generated by `bun run inventory`. Do not edit by hand.")
lines.push("")
lines.push("Rules:")
lines.push("")
lines.push("1. Check this file before creating a component.")
lines.push("2. Reuse or extend an existing component before adding a new one.")
lines.push("3. Removing code is preferred to adding code.")
lines.push("4. If variants are needed, keep them in one plural file with named exports and no default export.")
lines.push("5. Full apps go under `components/apps`; reusable app chunks go under `components/sections`; placement goes under `components/layouts`; primitives go under `components/ui`.")
lines.push("")
lines.push(`Total indexed files: ${entries.length}`)
lines.push("")

for (const [group, groupEntries] of Array.from(groups.entries()).sort(([a], [b]) => a.localeCompare(b))) {
  lines.push(`## ${group}`)
  lines.push("")
  for (const entry of groupEntries.sort((a, b) => a.path.localeCompare(b.path))) {
    lines.push(`- \`${entry.path}\``)
    if (entry.exports.length > 0) {
      lines.push(`  - exports: ${entry.exports.map((name) => `\`${name}\``).join(", ")}`)
    }
  }
  lines.push("")
}

writeFileSync(outputPath, `${lines.join("\n")}\n`)
writeFileSync(
  jsonOutputPath,
  `${JSON.stringify(
    {
      generatedBy: "scripts/generate-component-inventory.mjs",
      totalIndexedFiles: entries.length,
      entries,
    },
    null,
    2,
  )}\n`,
)
console.log(`Wrote ${relative(root, outputPath)}`)
console.log(`Wrote ${relative(root, jsonOutputPath)}`)
