#!/usr/bin/env node
"use strict";

const fs = require("fs");
const os = require("os");
const path = require("path");
const { spawnSync } = require("child_process");

const policy = require("../policy/app-policy-v0.js");

const port = path.resolve(__dirname, "..");
const source = path.join(port, "source/kernel");

function run(cmd, args, options = {}) {
  const result = spawnSync(cmd, args, {
    encoding: "utf8",
    maxBuffer: 1024 * 1024 * 32,
    ...options,
  });
  if (result.status !== 0) {
    throw new Error(
      `${cmd} ${args.join(" ")}\nstdout:\n${result.stdout || ""}\nstderr:\n${result.stderr || ""}`,
    );
  }
  return result;
}

function assemble(input, output) {
  run("yasm", ["-f", "elf64", "-I", source, "-o", output, input]);
}

function link(objects, output) {
  run("ld", ["-o", output, ...objects]);
}

function compileWat(watPath, wasmPath) {
  run("wat2wasm", ["--enable-annotations", watPath, "-o", wasmPath]);
}

function asmString(value) {
  return value
    .split("")
    .map((ch) => ch.charCodeAt(0))
    .join(",");
}

function asmCString(value) {
  return `${asmString(value)},0`;
}

function asmQwords(values) {
  return values.length === 0 ? "0" : values.map((value) => String(value)).join(",");
}

function stageRuntimeConfigAsm(memoryBytes = 65536) {
  return `    lea     rax, [rel linear_memory]
    mov     [runtime + RUNTIME_MEMORY_PTR_OFF], rax
    mov     qword [runtime + RUNTIME_MEMORY_LEN_OFF], ${memoryBytes}
    lea     rax, [rel ticks]
    mov     [runtime + RUNTIME_TICKS_PTR_OFF], rax
`;
}

function writeAbiCallHarness({ wasmPath, exportName, args, expected, output, dumpPath }) {
  const escapedWasmPath = wasmPath.replace(/\\/g, "\\\\").replace(/"/g, '\\"');
  const escapedDumpPath = dumpPath.replace(/\\/g, "\\\\");
  fs.writeFileSync(
    output,
    `; Generated by local-memory-sim.js
%define HAVE_ER_WASM_RUNTIME_PTR
%include "x86_64/wasm/wasm_interpreter.asm"
%include "test/test_macros.inc"

SECTION .data
wasm_bytes:
    incbin "${escapedWasmPath}"
wasm_bytes_end:
export_name: db ${asmString(exportName)}
EXPORT_NAME_LEN equ ${exportName.length}
args: dq ${asmQwords(args)}
dump_path: db ${asmCString(escapedDumpPath)}

SECTION .bss
runtime: resb RUNTIME_SIZE
linear_memory: resb 65536
ticks: resq 1

global er_wasm_runtime_ptr
er_wasm_runtime_ptr: resq 1

SECTION .text
global _start
_start:
${stageRuntimeConfigAsm()}\
    lea     rdi, [rel runtime]
    lea     rsi, [rel wasm_bytes]
    mov     rdx, wasm_bytes_end - wasm_bytes
    lea     rcx, [rel export_name]
    mov     r8, EXPORT_NAME_LEN
    lea     r9, [rel args]
    mov     rax, ${args.length}
    push    rax
    call    er_fn_run_args
    add     rsp, 8
    cmp     rdx, 1
    jne     .fail
    cmp     rax, ${expected}
    jne     .fail
    mov     rax, 85
    lea     rdi, [rel dump_path]
    mov     rsi, 420
    syscall
    cmp     rax, 0
    jl      .fail
    mov     r12, rax
    mov     rax, 1
    mov     rdi, r12
    lea     rsi, [rel linear_memory]
    mov     rdx, 65536
    syscall
    cmp     rax, 65536
    jne     .fail
    mov     rax, 3
    mov     rdi, r12
    syscall
    TEST_EXIT 0
.fail:
    TEST_EXIT 1
`,
  );
}

function runAbiCall({ wasmPath, outDir, runtimeMemObject, exportName, args, expected }) {
  const caseName = `${exportName}-${expected}`;
  const harness = path.join(outDir, `${caseName}.asm`);
  const object = path.join(outDir, `${caseName}.o`);
  const binary = path.join(outDir, caseName);
  const dumpPath = path.join(outDir, `${caseName}.linear-memory.bin`);
  writeAbiCallHarness({ wasmPath, exportName, args, expected, output: harness, dumpPath });
  assemble(harness, object);
  link([object, runtimeMemObject], binary);
  const result = spawnSync(binary, [], {
    cwd: outDir,
    encoding: "utf8",
    maxBuffer: 1024 * 1024 * 32,
  });
  if (result.status !== 0) {
    throw new Error(`${caseName}\n${result.stdout || ""}\n${result.stderr || ""}`);
  }
  return fs.readFileSync(dumpPath);
}

function asmByteData(bytes) {
  return bytes.length === 0 ? "0" : bytes.map((byte) => String(byte & 0xff)).join(",");
}

function writeTrustedExportHarness({
  wasmPath,
  exportName,
  args,
  expected,
  output,
  dumpPath,
  memoryBytes,
  memoryWrites,
}) {
  const escapedWasmPath = wasmPath.replace(/\\/g, "\\\\").replace(/"/g, '\\"');
  const escapedDumpPath = dumpPath.replace(/\\/g, "\\\\");
  const writeData = memoryWrites
    .map((write, index) => `memory_write_${index}: db ${asmByteData(write.bytes)}`)
    .join("\n");
  const writeAsm = memoryWrites
    .map(
      (write, index) => `    lea     rdi, [rel linear_memory + ${write.offset}]
    lea     rsi, [rel memory_write_${index}]
    mov     rcx, ${write.bytes.length}
    rep movsb`,
    )
    .join("\n");
  fs.writeFileSync(
    output,
    `; Generated by local-memory-sim.js
%define HAVE_ER_WASM_RUNTIME_PTR
%include "x86_64/wasm/wasm_interpreter.asm"
%include "test/test_macros.inc"

SECTION .data
wasm_bytes:
    incbin "${escapedWasmPath}"
wasm_bytes_end:
export_name: db ${asmString(exportName)}
EXPORT_NAME_LEN equ ${exportName.length}
args: dq ${asmQwords(args)}
dump_path: db ${asmCString(escapedDumpPath)}
${writeData}

SECTION .bss
runtime: resb RUNTIME_SIZE
linear_memory: resb ${memoryBytes}
ticks: resq 1

global er_wasm_runtime_ptr
er_wasm_runtime_ptr: resq 1

SECTION .text
global _start
_start:
${stageRuntimeConfigAsm(memoryBytes)}\
${writeAsm}
    lea     rdi, [rel runtime]
    lea     rsi, [rel wasm_bytes]
    mov     rdx, wasm_bytes_end - wasm_bytes
    call    er_fn_load_trusted
    cmp     rdx, 0
    jne     .fail
    lea     rdi, [rel runtime]
    lea     rsi, [rel export_name]
    mov     rdx, EXPORT_NAME_LEN
    lea     rcx, [rel args]
    mov     r8, ${args.length}
    call    er_fn_call_args
    cmp     rdx, 0
    jne     .fail
    cmp     rax, ${expected}
    jne     .fail
    mov     rax, 85
    lea     rdi, [rel dump_path]
    mov     rsi, 420
    syscall
    cmp     rax, 0
    jl      .fail
    mov     r12, rax
    mov     rax, 1
    mov     rdi, r12
    lea     rsi, [rel linear_memory]
    mov     rdx, ${memoryBytes}
    syscall
    cmp     rax, ${memoryBytes}
    jne     .fail
    mov     rax, 3
    mov     rdi, r12
    syscall
    TEST_EXIT 0
.fail:
    TEST_EXIT 1
`,
  );
}

function callExportAsm({ exportLabel, exportLenLabel, argsLabel, argCount, expected }) {
  return `    lea     rdi, [rel runtime]
    lea     rsi, [rel ${exportLabel}]
    mov     rdx, ${exportLenLabel}
    lea     rcx, [rel ${argsLabel}]
    mov     r8, ${argCount}
    call    er_fn_call_args
    cmp     rdx, 0
    jne     .fail
    cmp     rax, ${expected}
    jne     .fail`;
}

function memoryWritesAsm(memoryWrites, prefix) {
  return memoryWrites
    .filter((write) => write.bytes.length > 0)
    .map(
      (write, index) => `    lea     rdi, [rel linear_memory + ${write.offset}]
    lea     rsi, [rel ${prefix}_write_${index}]
    mov     rcx, ${write.bytes.length}
    rep movsb`,
    )
    .join("\n");
}

function memoryWritesData(memoryWrites, prefix) {
  return memoryWrites
    .filter((write) => write.bytes.length > 0)
    .map((write, index) => `${prefix}_write_${index}: db ${asmByteData(write.bytes)}`)
    .join("\n");
}

function writeTrustedCallSequenceHarness({
  wasmPath,
  calls,
  output,
  dumpPath,
  memoryBytes,
}) {
  const escapedWasmPath = wasmPath.replace(/\\/g, "\\\\").replace(/"/g, '\\"');
  const escapedDumpPath = dumpPath.replace(/\\/g, "\\\\");
  const callData = calls
    .map((call, index) => {
      const prefix = `call_${index}`;
      return [
        `${prefix}_export: db ${asmString(call.exportName)}`,
        `${prefix}_EXPORT_LEN equ ${call.exportName.length}`,
        `${prefix}_args: dq ${asmQwords(call.args || [])}`,
        memoryWritesData(call.memoryWrites || [], prefix),
      ]
        .filter(Boolean)
        .join("\n");
    })
    .join("\n");
  const callAsm = calls
    .map((call, index) => {
      const prefix = `call_${index}`;
      return [
        memoryWritesAsm(call.memoryWrites || [], prefix),
        callExportAsm({
          exportLabel: `${prefix}_export`,
          exportLenLabel: `${prefix}_EXPORT_LEN`,
          argsLabel: `${prefix}_args`,
          argCount: (call.args || []).length,
          expected: call.expected,
        }),
      ]
        .filter(Boolean)
        .join("\n");
    })
    .join("\n");

  fs.writeFileSync(
    output,
    `; Generated by local-memory-sim.js
%define HAVE_ER_WASM_RUNTIME_PTR
%include "x86_64/wasm/wasm_interpreter.asm"
%include "test/test_macros.inc"

SECTION .data
wasm_bytes:
    incbin "${escapedWasmPath}"
wasm_bytes_end:
dump_path: db ${asmCString(escapedDumpPath)}
${callData}

SECTION .bss
runtime: resb RUNTIME_SIZE
linear_memory: resb ${memoryBytes}
ticks: resq 1

global er_wasm_runtime_ptr
er_wasm_runtime_ptr: resq 1

SECTION .text
global _start
_start:
${stageRuntimeConfigAsm(memoryBytes)}\
    lea     rdi, [rel runtime]
    lea     rsi, [rel wasm_bytes]
    mov     rdx, wasm_bytes_end - wasm_bytes
    call    er_fn_load_trusted
    cmp     rdx, 0
    jne     .fail
${callAsm}
    mov     rax, 85
    lea     rdi, [rel dump_path]
    mov     rsi, 420
    syscall
    cmp     rax, 0
    jl      .fail
    mov     r12, rax
    mov     rax, 1
    mov     rdi, r12
    lea     rsi, [rel linear_memory]
    mov     rdx, ${memoryBytes}
    syscall
    cmp     rax, ${memoryBytes}
    jne     .fail
    mov     rax, 3
    mov     rdi, r12
    syscall
    TEST_EXIT 0
.fail:
    TEST_EXIT 1
`,
  );
}

function runTrustedWatExportMemory({
  watPath,
  exportName,
  args = [],
  expected,
  memoryBytes = 1114112,
  memoryWrites = [],
  workDir = null,
} = {}) {
  if (!watPath) {
    throw new Error("runTrustedWatExportMemory requires watPath");
  }
  if (!exportName) {
    throw new Error("runTrustedWatExportMemory requires exportName");
  }
  const outDir = workDir || fs.mkdtempSync(path.join(os.tmpdir(), "edgerun-trusted-wat-export-"));
  const wasmPath = path.join(outDir, `${path.basename(watPath, ".wat")}.wasm`);
  compileWat(watPath, wasmPath);

  const runtimeMemObject = path.join(outDir, "runtime_mem_unit.o");
  const caseName = `${exportName}-${expected}`;
  const harness = path.join(outDir, `${caseName}.asm`);
  const object = path.join(outDir, `${caseName}.o`);
  const binary = path.join(outDir, caseName);
  const dumpPath = path.join(outDir, `${caseName}.linear-memory.bin`);
  assemble(path.join(source, "x86_64/rt/runtime_mem_unit.asm"), runtimeMemObject);
  writeTrustedExportHarness({
    wasmPath,
    exportName,
    args,
    expected,
    output: harness,
    dumpPath,
    memoryBytes,
    memoryWrites,
  });
  assemble(harness, object);
  link([object, runtimeMemObject], binary);
  const result = spawnSync(binary, [], {
    cwd: outDir,
    encoding: "utf8",
    maxBuffer: 1024 * 1024 * 32,
  });
  if (result.status !== 0) {
    throw new Error(`${caseName}\n${result.stdout || ""}\n${result.stderr || ""}`);
  }
  return fs.readFileSync(dumpPath);
}

function runTrustedWatCallSequenceMemory({
  watPath,
  calls = [],
  memoryBytes = 1114112,
  workDir = null,
} = {}) {
  if (!watPath) {
    throw new Error("runTrustedWatCallSequenceMemory requires watPath");
  }
  if (calls.length === 0) {
    throw new Error("runTrustedWatCallSequenceMemory requires calls");
  }
  const outDir = workDir || fs.mkdtempSync(path.join(os.tmpdir(), "edgerun-trusted-wat-sequence-"));
  const wasmPath = path.join(outDir, `${path.basename(watPath, ".wat")}.wasm`);
  compileWat(watPath, wasmPath);

  const runtimeMemObject = path.join(outDir, "runtime_mem_unit.o");
  const harness = path.join(outDir, "trusted-call-sequence.asm");
  const object = path.join(outDir, "trusted-call-sequence.o");
  const binary = path.join(outDir, "trusted-call-sequence");
  const dumpPath = path.join(outDir, "trusted-call-sequence.linear-memory.bin");
  assemble(path.join(source, "x86_64/rt/runtime_mem_unit.asm"), runtimeMemObject);
  writeTrustedCallSequenceHarness({
    wasmPath,
    calls,
    output: harness,
    dumpPath,
    memoryBytes,
  });
  assemble(harness, object);
  link([object, runtimeMemObject], binary);
  const result = spawnSync(binary, [], {
    cwd: outDir,
    encoding: "utf8",
    maxBuffer: 1024 * 1024 * 32,
  });
  if (result.status !== 0) {
    throw new Error(`trusted-call-sequence\n${result.stdout || ""}\n${result.stderr || ""}`);
  }
  return fs.readFileSync(dumpPath);
}

function runWatExportMemory({
  watPath,
  exportName,
  args = [],
  expected,
  workDir = null,
} = {}) {
  if (!watPath) {
    throw new Error("runWatExportMemory requires watPath");
  }
  if (!exportName) {
    throw new Error("runWatExportMemory requires exportName");
  }
  const outDir = workDir || fs.mkdtempSync(path.join(os.tmpdir(), "edgerun-wat-export-"));
  const wasmPath = path.join(outDir, `${path.basename(watPath, ".wat")}.wasm`);
  compileWat(watPath, wasmPath);

  const runtimeMemObject = path.join(outDir, "runtime_mem_unit.o");
  assemble(path.join(source, "x86_64/rt/runtime_mem_unit.asm"), runtimeMemObject);

  return runAbiCall({
    wasmPath,
    outDir,
    runtimeMemObject,
    exportName,
    args,
    expected,
  });
}

function simulateWatApp({
  watPath,
  initCall = { exportName: "er_init", args: [64], expectedPtr: 64 },
  transitionCalls = [
    { exportName: "er_handle_message", args: [64, 640, 16], expectedPtr: 96 },
    { exportName: "er_handle_action", args: [64, 768, 8], expectedPtr: 352 },
  ],
  renderCall = { exportName: "er_render", args: [64], expectedPtr: 896 },
  validate = true,
  workDir = null,
} = {}) {
  if (!watPath) {
    throw new Error("simulateWatApp requires watPath");
  }
  const outDir = workDir || fs.mkdtempSync(path.join(os.tmpdir(), "edgerun-local-memory-sim-"));
  const wasmPath = path.join(outDir, `${path.basename(watPath, ".wat")}.wasm`);
  compileWat(watPath, wasmPath);

  const runtimeMemObject = path.join(outDir, "runtime_mem_unit.o");
  assemble(path.join(source, "x86_64/rt/runtime_mem_unit.asm"), runtimeMemObject);

  const initMemory = runAbiCall({
    wasmPath,
    outDir,
    runtimeMemObject,
    exportName: initCall.exportName,
    args: initCall.args,
    expected: initCall.expectedPtr,
  });

  const manifest = policy.manifestPolicy(wasmPath);
  policy.assertAppAbi(wasmPath, "local-memory-sim", manifest);

  const appId = Buffer.from(policy.wasmHash(wasmPath), "hex");
  const transitions = [];
  let clock = 0;
  let previousHash = Buffer.alloc(32, 0);
  for (const call of transitionCalls) {
    const memory = runAbiCall({
      wasmPath,
      outDir,
      runtimeMemObject,
      exportName: call.exportName,
      args: call.args,
      expected: call.expectedPtr,
    });
    const transition = policy.decodeTransition(memory, call.expectedPtr);
    if (validate) {
      policy.assertTransitionIdentityPolicy("local-memory-sim", appId, appId);
      policy.assertTransitionPolicy("local-memory-sim", transition, manifest);
    }
    clock += transition.clockDelta;
    previousHash = policy.eventHash({ appId, clock, previousHash, transition });
    transitions.push({
      exportName: call.exportName,
      hash: previousHash.toString("hex"),
      transition,
    });
  }

  const renderMemory = runAbiCall({
    wasmPath,
    outDir,
    runtimeMemObject,
    exportName: renderCall.exportName,
    args: renderCall.args,
    expected: renderCall.expectedPtr,
  });
  const render = policy.decodeRender(renderMemory, renderCall.expectedPtr);
  if (validate) {
    policy.assertRenderPolicy("local-memory-sim", render, manifest);
  }

  return {
    appId: appId.toString("hex"),
    clock,
    eventHash: previousHash.toString("hex"),
    init: {
      ptr: initCall.expectedPtr,
      marker: initMemory.readUInt32LE(initCall.expectedPtr),
    },
    manifest,
    render,
    transitions,
    wasmPath,
  };
}

if (require.main === module) {
  const watPath = process.argv[2] || path.join(port, "tests/app-abi-v0.wat");
  const result = simulateWatApp({ watPath });
  process.stdout.write(`${JSON.stringify(result, null, 2)}\n`);
}

module.exports = {
  decodeRender: policy.decodeRender,
  decodeTransition: policy.decodeTransition,
  eventHash: policy.eventHash,
  manifest: policy.manifestPolicy,
  runTrustedWatCallSequenceMemory,
  runTrustedWatExportMemory,
  runWatExportMemory,
  simulateWatApp,
};
