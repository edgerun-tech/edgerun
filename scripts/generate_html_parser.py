def generate_entity_decoder_rs(ir):
    entities = ir["entities"]

    # Build a simple lookup: "&name;" → (char1, char2)
    entity_entries = []
    for e in entities:
        name = e["name"]
        cp1 = e["code_point_1"]
        cp2 = e["code_point_2"]
        char1 = f"char::from_u32({cp1}).unwrap()"
        if cp2:
            char2 = f"char::from_u32({cp2}).unwrap()"
            entity_entries.append(f'        "{name}" => Some(({char1}, Some({char2}))),')
        else:
            entity_entries.append(f'        "{name}" => Some(({char1}, None)),')

    entries_str = "\n".join(entity_entries)

    code = f"""{HEADER}
extern crate alloc;

use alloc::string::String;

/// Entity decoder — maps named character references to Unicode code points.
///
/// Generated from Parser IR with {len(entities)} entities.
/// Phase 1: minimal set (5 entities). Full spec has 2,231.
pub struct EntityDecoder;

impl EntityDecoder {{
    /// Decode a named entity (without & or ;).
    /// Returns (primary_char, optional_secondary_char) or None.
    pub fn decode(name: &str) -> Option<(char, Option<char>)> {{
        match name {{
{entries_str}
            _ => None,
        }}
    }}

    /// Decode a full entity reference including & and optionally ;.
    pub fn decode_full(input: &str) -> Option<(String, usize)> {{
        if !input.starts_with('&') {{
            return None;
        }}
        // Try to find the entity name
        let rest = &input[1..];
        let semi_pos = rest.find(';');
        if let Some(pos) = semi_pos {{
            let name = &rest[..pos];
            if let Some((c1, c2)) = Self::decode(name) {{
                let s = if let Some(c2) = c2 {{
                    format!("{{}}{{}}", c1, c2)
                }} else {{
                    format!("{{}}", c1)
                }};
                return Some((s, pos + 2)); // +2 for & and ;
            }}
        }}
        // Try without semicolon (for legacy entities)
        for len in (1..=rest.len()).rev() {{
            let name = &rest[..len];
            if let Some((c1, c2)) = Self::decode(name) {{
                let s = if let Some(c2) = c2 {{
                    format!("{{}}{{}}", c1, c2)
                }} else {{
                    format!("{{}}", c1)
                }};
                return Some((s, len + 1)); // +1 for &
            }}
        }}
        None
    }}
}}
"""
    return code


