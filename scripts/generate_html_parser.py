def classify_char(c):
    """Map a Rust char to a char class string matching the IR."""
    if c == '\x00':
        return "NULL"
    if c == '<':
        return "LT"
    if c == '>':
        return "GT"
    if c == '/':
        return "SLASH"
    if c == '&':
        return "AMP"
    if c == '"':
        return "QUOT"
    if c == '\'':
        return "APOS"
    if c == '=':
        return "EQ"
    if c in (' ', '\t', '\n', '\r', '\x0c'):
        return "WS"
    if c.isascii_alpha():
        return "ALPHA"
    if c.isascii_alphanumeric() or c in ('-', '_'):
        return "ALNUM"
    return "OTHER"


def rust_char_literal(c):
    """Escape a char for Rust char literal."""
    if c == '\x00':
        return "'\\0'"
    if c == '\\':
        return "'\\\\'"
    if c == "'":
        return "'\\''"
    return f"'{c}'"


def generate_tokenizer_rs(ir):
    states = ir["states"]
    transitions = ir["transitions"]
    void_elements = ir["void_elements"]
    raw_text_elements = ir["raw_text_elements"]

    # Build transition table: state → char_class → next_state, actions
    # For codegen, we generate a match arm for each state,
    # and inside each state, a match on the char class.

    # Group transitions by (state, char_class)
    from collections import defaultdict
    state_trans = defaultdict(list)
    for t in transitions:
        state_trans[(t["state"], t["char_class"])].append(t)

    # Build state machine code
    state_match_arms = []
    for state_name, state_id in sorted(states.items(), key=lambda x: x[1]):
        rust_state = camel_case(state_name)

        # Get all transitions for this state
        state_transitions = [(k_c, v) for (k_s, k_c), v in state_trans.items() if k_s == state_name]

        char_class_arms = []
        # Sort so that OTHER ("_") wildcard arm is always LAST
        sorted_transitions = sorted(state_transitions, key=lambda x: (x[0] == "OTHER", x[0]))
        for char_class, trans_list in sorted_transitions:
            if len(trans_list) != 1:
                # Multiple transitions for same (state, char_class) — shouldn't happen in valid IR
                continue
            t = trans_list[0]
            next_state = camel_case(t["next"])
            actions = t["actions"]

            # Build the action code
            action_lines = []
            for action in actions:
                if action == "EMIT_CHAR":
                    action_lines.append("self.emit_char();")
                elif action == "EMIT_EOF":
                    action_lines.append("self.done = true;")
                elif action == "START_TAG":
                    action_lines.append("self.start_tag();")
                elif action == "END_TAG":
                    action_lines.append("self.end_tag();")
                elif action == "APPEND_TAG_NAME":
                    action_lines.append("self.append_tag_name(c);")
                elif action == "APPEND_ATTR_NAME":
                    action_lines.append("self.append_attr_name(c);")
                elif action == "APPEND_ATTR_VALUE":
                    action_lines.append("self.append_attr_value(c);")
                elif action == "EMIT_TOKEN":
                    action_lines.append("self.emit_tag();")
                elif action == "SET_SELF_CLOSING":
                    action_lines.append("self.current_token_is_self_closing = true;")
                elif action == "PARSE_ERROR":
                    action_lines.append("self.parse_errors += 1;")

            action_code = "\n                    ".join(action_lines) if action_lines else ""

            # Determine the character match pattern
            if char_class == "ALPHA":
                pattern = "'a'..='z' | 'A'..='Z'"
            elif char_class == "ALNUM":
                pattern = "'a'..='z' | 'A'..='Z' | '0'..='9' | '-' | '_'"
            elif char_class == "WS":
                pattern = "' ' | '\\t' | '\\n' | '\\r' | '\\x0C'"
            elif char_class == "OTHER":
                pattern = "_"
            elif char_class == "NULL":
                pattern = "'\\0'"
            elif char_class == "EOF":
                # EOF is handled at the input level, not in the match
                continue
            else:
                raw_char = {
                    "LT": '<',
                    "GT": '>',
                    "SLASH": '/',
                    "AMP": '&',
                    "QUOT": '"',
                    "APOS": "'",
                    "EQ": '=',
                }.get(char_class, '_')
                pattern = rust_char_literal(raw_char)

            arm = f"                {pattern} => {{\n                    self.state = State::{next_state};\n                    {action_code}\n                }}"
            char_class_arms.append(arm)

        # Default fallthrough for EOF — stay in state
        if "EOF" not in [t.get("char_class") for t in transitions if t.get("state") == state_name]:
            pass  # No EOF transition defined for this state, no arm needed

        arm_body = "\n".join(char_class_arms)
        if not arm_body:
            # No transitions for this state — just stay
            state_match_arms.append(f"""\
            State::{rust_state} => {{
                // No transitions defined — stays in state
            }}""")
        else:
            state_match_arms.append(f"""\
            State::{rust_state} => {{
                match c {{
{arm_body}
                }}
            }}""")

    arms_str = "\n\n".join(state_match_arms)

    # Build the full file
    code = f"""{HEADER}
extern crate alloc;

use alloc::string::{{String, ToString}};
use alloc::vec::Vec;
use alloc::collections::BTreeMap;

use crate::html_parser::{{Node, Element}};

/// Token types emitted by the tokenizer.
#[derive(Debug, Clone)]
pub enum Token {{
    StartTag {{ name: String, attrs: BTreeMap<String, String>, self_closing: bool }},
    EndTag {{ name: String }},
    Character(String),
    Comment(String),
    Eof,
}}

/// Tokenizer states from WHATWG §13.2.5.
#[derive(Debug, Clone, PartialEq, Eq)]
enum State {{
    Data,
    TagOpen,
    EndTagOpen,
    TagName,
    BeforeAttributeName,
    AttributeName,
    AfterAttributeName,
    BeforeAttributeValue,
    AttributeValueDoubleQuoted,
    AttributeValueSingleQuoted,
    AttributeValueUnquoted,
    SelfClosingStartTag,
    Eof,
}}

/// WHATWG §13.2.5 HTML tokenizer — table-driven state machine.
///
/// Generated from Parser IR with {len(transitions)} transitions across {len(states)} states.
/// Each input character maps to a char class, which indexes into the transition table.
pub struct Tokenizer {{
    input: Vec<char>,
    pos: usize,
    state: State,
    current_tag_name: String,
    current_attr_name: String,
    current_attr_value: String,
    current_attr_map: BTreeMap<String, String>,
    current_token_is_self_closing: bool,
    text_buffer: String,
    pending_token: Option<Token>,
    is_start_tag: bool,
    parse_errors: usize,
    done: bool,
}}

impl Tokenizer {{
    pub fn new(input: &str) -> Self {{
        Self {{
            input: input.chars().collect(),
            pos: 0,
            state: State::Data,
            current_tag_name: String::new(),
            current_attr_name: String::new(),
            current_attr_value: String::new(),
            current_attr_map: BTreeMap::new(),
            current_token_is_self_closing: false,
            text_buffer: String::new(),
            pending_token: None,
            is_start_tag: false,
            parse_errors: 0,
            done: false,
        }}
    }}

    /// Run the tokenizer to completion, returning all tokens.
    pub fn tokenize(&mut self) -> Vec<Token> {{
        let mut tokens = Vec::new();
        while let Some(token) = self.step() {{
            tokens.push(token);
        }}
        tokens
    }}

    /// Step the state machine until a token is emitted or we're done.
    /// Returns None only when fully finished (EOF emitted).
    fn step(&mut self) -> Option<Token> {{
        loop {{
            // Return any pending token from previous step
            if let Some(t) = self.pending_token.take() {{
                return Some(t);
            }}

            if self.pos >= self.input.len() {{
                if !self.done {{
                    // Flush buffered text
                    if !self.text_buffer.is_empty() {{
                        let t = Token::Character(self.text_buffer.clone());
                        self.text_buffer.clear();
                        return Some(t);
                    }}
                    self.done = true;
                    return Some(Token::Eof);
                }}
                return None;
            }}

            let c = self.input[self.pos];

            // When in DATA state and we see '<', flush buffered text first
            if self.state == State::Data && c == '<' && !self.text_buffer.is_empty() {{
                let t = Token::Character(self.text_buffer.clone());
                self.text_buffer.clear();
                // Don't consume '<' yet — process it on next step
                return Some(t);
            }}

            self.pos += 1;

            match self.state {{
{arms_str}
            }}
            // If no pending token was set, continue loop to next character
        }}
    }}

    fn emit_char(&mut self) {{
        // Only emit non-whitespace or if we have content
        self.text_buffer.push(self.input[self.pos - 1]);
    }}

    fn start_tag(&mut self) {{
        self.current_tag_name.clear();
        self.current_attr_name.clear();
        self.current_attr_value.clear();
        self.current_attr_map.clear();
        self.current_token_is_self_closing = false;
        self.is_start_tag = true;
    }}

    fn end_tag(&mut self) {{
        self.current_tag_name.clear();
        self.is_start_tag = false;
    }}

    fn append_tag_name(&mut self, c: char) {{
        self.current_tag_name.push(c.to_ascii_lowercase());
    }}

    fn append_attr_name(&mut self, c: char) {{
        self.current_attr_name.push(c);
    }}

    fn append_attr_value(&mut self, c: char) {{
        self.current_attr_value.push(c);
    }}

    fn emit_tag(&mut self) {{
        let tag = self.current_tag_name.clone();
        let attrs = self.current_attr_map.clone();
        let self_closing = self.current_token_is_self_closing;

        if self.is_start_tag {{
            self.pending_token = Some(Token::StartTag {{ name: tag, attrs, self_closing }});
        }} else {{
            self.pending_token = Some(Token::EndTag {{ name: tag }});
        }}
    }}

    pub fn parse_errors(&self) -> usize {{
        self.parse_errors
    }}
}}

/// Raw text element tags that switch the tokenizer to RAWTEXT mode.
pub const RAW_TEXT_ELEMENTS: &[&str] = &{json.dumps(raw_text_elements)};

/// Void element tags that never have children.
pub const VOID_ELEMENTS: &[&str] = &{json.dumps(void_elements)};
"""
    return code


